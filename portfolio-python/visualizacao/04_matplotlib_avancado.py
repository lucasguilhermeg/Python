"""### Visualização de dados 101:"""

# Criando um gráfico no matplotlib:
import matplotlib.pyplot as plt


dados_x = [1, 3, 5, 7, 9]
dados_y = [1, 9, 25, 49, 81]

plt.plot(dados_x, dados_y)
plt.show()

"""### Customizando o gráfico:
Vamos adicionar algumas customizações ao nosso gráfico como mudar a cor e estilo da linha, adicionar marcadores, legendas nos eixos e rotular os dados.
"""

plt.plot(dados_x,
         dados_y,
         marker='*',
         color='green',
         linewidth=1.5,
         linestyle='--',
         label=r'f(x) = $x^{2}$')

plt.legend()
plt.xlabel("x", fontsize=12)
plt.ylabel("f(x)", fontsize=12)

plt.savefig('grafico.png', dpi=300)
plt.show()

