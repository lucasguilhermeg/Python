plt.style.use('default')
import numpy  as np

def f(x):
  return x**3

dominio = np.linspace(0, 1, 100)

plt.plot(dominio,
         f(dominio),
         color='blue',
         ls='--',
         lw=1.25,
         label=r'f(x) = $\omega$')

plt.legend(frameon=False, loc="upper left")
plt.title(r'f(x) = $x^{3}$', fontsize=15)
plt.xlabel("x", fontsize=12)
plt.ylabel("f(x)", fontsize=12)

plt.show()

